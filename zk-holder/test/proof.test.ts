import { resolve } from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { decodeAbiParameters, hexToBigInt } from "viem";

import { credentialCommitment, expiryOf } from "../src/credential.js";
import { CREDENTIAL_TREE_DEPTH, JURISDICTION_TREE_DEPTH } from "../src/field.js";
import {
  attestorArguments,
  circuitArtifacts,
  proveCompliance,
  releaseProver,
  verifyLocally,
  type ComplianceProof,
} from "../src/prover.js";
import { generateHolderSecret, holderSecretHash } from "../src/secret.js";
import { buildWitness, WitnessError, type WitnessParameters } from "../src/witness.js";
import { issuerModules } from "./helpers/issuer.js";

const artifacts = circuitArtifacts(resolve(import.meta.dirname, "../../zk-circuits/build"));
const ASSET_ID = 84532001n;
const EPOCH_LENGTH = 2_592_000n;
const EPOCH_END = 1_796_256_000n;
const ANCHOR = 0x1234_5678_9abc_def0_1234_5678_9abc_def0n;

let params: WitnessParameters;
let proof: ComplianceProof;

beforeAll(async () => {
  const { merkle, poseidon } = await issuerModules();
  const hash = await poseidon.poseidonHash();
  const secret = generateHolderSecret();
  const expiry = expiryOf("2027-03-01T00:00:00Z");
  const commitment = await credentialCommitment(await holderSecretHash(secret), 170, expiry);

  const credentials = new merkle.SparseMerkleTree(CREDENTIAL_TREE_DEPTH, hash);
  credentials.setLeaf(0, 987654321n);
  credentials.setLeaf(1, commitment);
  const jurisdictions = new merkle.SparseMerkleTree(JURISDICTION_TREE_DEPTH, hash);
  [170, 484, 604].forEach((code, index) => jurisdictions.setLeaf(index, BigInt(code)));

  params = {
    secret,
    countryCode: 170,
    expiry,
    assetId: ASSET_ID,
    epochEnd: EPOCH_END,
    anchor: ANCHOR,
    credential: {
      commitment: commitment.toString(),
      leafIndex: 1,
      credentialRoot: credentials.root().toString(),
      opening: credentials.opening(1),
    },
    jurisdiction: {
      assetId: ASSET_ID.toString(),
      countryCode: 170,
      leafIndex: 0,
      countryRoot: jurisdictions.root().toString(),
      opening: jurisdictions.opening(0),
    },
  };
  proof = await proveCompliance((await buildWitness(params)).input, artifacts);
});

afterAll(async () => {
  await releaseProver();
});

describe("proof generated by the holder", () => {
  it("verifies against the verifying key of the deployed verifier", async () => {
    expect(await verifyLocally(proof, artifacts.verificationKeyPath)).toBe(true);
  });

  it("publishes the six signals in the circuit's order", async () => {
    const witness = await buildWitness(params);
    expect(proof.publicSignals).toEqual([
      params.credential.credentialRoot,
      params.jurisdiction.countryRoot,
      ASSET_ID.toString(),
      EPOCH_END.toString(),
      witness.nullifier.toString(),
      ANCHOR.toString(),
    ]);
    expect(proof.callData.signals.map((value) => hexToBigInt(value).toString())).toEqual(proof.publicSignals);
  });

  it("stops verifying when any public signal is moved", async () => {
    for (let index = 0; index < 6; index += 1) {
      const moved = [...proof.publicSignals];
      moved[index] = (BigInt(moved[index]!) + 1n).toString();
      expect(await verifyLocally({ ...proof, publicSignals: moved }, artifacts.verificationKeyPath)).toBe(false);
    }
  });

  it("encodes 256 bytes for attestFor and the same signals", () => {
    const { proof: body, signals } = attestorArguments(proof.callData);
    expect((body.length - 2) / 2).toBe(256);
    const [a, b, c] = decodeAbiParameters(
      [{ type: "uint256[2]" }, { type: "uint256[2][2]" }, { type: "uint256[2]" }],
      body,
    );
    expect(a.map(String)).toEqual(proof.callData.a.map((v) => hexToBigInt(v).toString()));
    expect(b[0].map(String)).toEqual(proof.callData.b[0].map((v) => hexToBigInt(v).toString()));
    expect(c.map(String)).toEqual(proof.callData.c.map((v) => hexToBigInt(v).toString()));
    expect(signals.map(String)).toEqual(proof.publicSignals);
  });

  it("names an inconsistent input before proving", async () => {
    await expect(buildWitness({ ...params, countryCode: 484 })).rejects.toBeInstanceOf(WitnessError);
    await expect(buildWitness({ ...params, epochEnd: params.expiry + EPOCH_LENGTH })).rejects.toThrow(/expires before/);
  });

  it("cannot prove a jurisdiction the asset does not admit, even past the client's own checks", async () => {
    const outsider = await buildWitness({ ...params, countryCode: 840 }, { check: false });
    await expect(proveCompliance(outsider.input, artifacts)).rejects.toThrow(/Assert Failed/);
  });
});
